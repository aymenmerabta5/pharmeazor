NOTICE_COLUMNS = [
    "document_id", "medication_id", "document_type", "original_filename",
    "source_name", "source_id", "source_url", "direct_document_url",
    "manufacturer", "country", "language", "strength", "pharmaceutical_form",
    "revision_or_publication_date", "collection_date", "registration_number",
    "collection_method", "verification_status", "local_file_path",
    "original_file_path", "medicine_name", "brand_name", "dci",
    "notice_sha256", "match_evidence",
]
REFERENCE_STATUSES = (FOUND, NOT_FOUND_IN_DOCUMENT, NEEDS_REVIEW)

# Independent markers, deliberately simpler than the production detector.
PROVISIONAL_MARKERS = {
    "indications": r"(?:qu['’]est[- ]ce que|dans quels cas|what is .{0,80}?(?:used|for)|"
                   r"what are .{0,80}? for)",
    "posologie": r"(?:comment (?:utiliser|prendre)|how (?:should i|to) (?:take|use)|"
                 r"mode d['’]emploi)",
    "contre_indications": r"(?:ne prenez jamais|ne pas (?:prendre|utiliser)|"
                          r"do not (?:take|use)|who should not)",
    "interactions": r"(?:autres m[ée]dicaments|other medicines|taking other medicines|"
                    r"interactions? m[ée]dicament)",
    "effets_indesirables": r"(?:effets? ind[ée]sirables?|side effects?|"
                           r"adverse (?:effects?|reactions?))",
}
_PROVISIONAL_RE = {key: re.compile(pattern, re.I)
                   for key, pattern in PROVISIONAL_MARKERS.items()}
_ALL_MARKERS = re.compile("|".join(f"(?:{pattern})" for pattern in
                                   PROVISIONAL_MARKERS.values()), re.I)


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _notice_text(row: dict) -> str:
    for field in ("local_file_path", "original_file_path"):
        path = resolve_path(row.get(field, ""))
        if path.exists() and path.suffix.lower() in (".txt", ".md", ""):
            return strip_notice_header(read_text_auto(path))
    # scanned/PDF notices: fall back to the extracted text produced earlier
    for field in ("original_file_path", "local_file_path"):
        path = resolve_path(row.get(field, ""))
        if path.exists():
            try:
                import pymupdf
                with pymupdf.open(path) as doc:
                    return "\n".join(page.get_text() for page in doc)
            except Exception:
                continue
    return ""


def _sample_id(index: int) -> str:
    return f"EVAL{index:03d}"


def _stratified(rows: list[dict], size: int) -> list[dict]:
    """Proportional sample that guarantees every source/language group."""
    groups: dict[tuple, list[dict]] = {}
    for row in rows:
        key = (row.get("source_id", ""), row.get("language", ""))
        groups.setdefault(key, []).append(row)
    for values in groups.values():
        values.sort(key=lambda row: hashlib.sha256(
            row.get("document_id", "").encode("utf-8")).hexdigest())
    chosen: list[dict] = []
    chosen_ids: set[str] = set()
    total = len(rows)
    # proportional allocation, minimum one per group
    for key, values in sorted(groups.items()):
        want = max(1, round(size * len(values) / total)) if total else 1
        for row in values[:want]:
            if len(chosen) >= size:
                break
            if row["document_id"] not in chosen_ids:
                chosen.append(row)
                chosen_ids.add(row["document_id"])
    # fill any remaining slots from the stable global order
    rest = sorted(rows, key=lambda row: hashlib.sha256(
        row.get("document_id", "").encode("utf-8")).hexdigest())
    for row in rest:
        if len(chosen) >= size:
            break
        if row["document_id"] not in chosen_ids:
            chosen.append(row)
            chosen_ids.add(row["document_id"])
    return chosen[:size]


def build_sample(size: int = 20, refresh: bool = False) -> pd.DataFrame:
    """Select a deterministic, stratified sample of patient notices."""
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    if EVAL_SAMPLE_CSV.exists() and not refresh:
        existing = read_table(EVAL_SAMPLE_CSV, EVAL_SAMPLE_COLUMNS)
        if not existing.empty:
            return existing

    frame = read_table(META_DIR / "notices.csv", NOTICE_COLUMNS)
    rows = []
    for row in frame.to_dict("records"):
        if not _notice_text(row).strip():
            continue
        rows.append(row)
    sample = _stratified(rows, size)
    out = []
    for index, row in enumerate(sample, start=1):
        out.append({
            "sample_id": _sample_id(index),
            "document_id": row.get("document_id", ""),
            "medication_id": row.get("medication_id", ""),
            "source_id": row.get("source_id", ""),
            "language": row.get("language", ""),
            "file_path": row.get("original_file_path")
            or row.get("local_file_path", ""),
            "selection_reason": (f"stratified notice sample "
                                 f"(source={row.get('source_id', '')}, "
                                 f"language={row.get('language', '')})"),
            "sampled_at": _now(),
            "reviewer": "",
            "notes": "",
        })
    result = pd.DataFrame(out, columns=EVAL_SAMPLE_COLUMNS)
    write_table(EVAL_SAMPLE_CSV, result)
    return result


def build_reference_template(sample: pd.DataFrame) -> pd.DataFrame:
    """Create/extend the human reference without overwriting annotations."""
    existing = read_table(EVAL_REFERENCE_CSV, EVAL_REFERENCE_COLUMNS)
    key_columns = ["sample_id", "document_id", "section_key"]
    existing_keys = set()
    if not existing.empty:
        existing_keys = {tuple(row[column] for column in key_columns)
                         for _, row in existing.iterrows()}
    rows = existing.to_dict("records") if not existing.empty else []
    for _, entry in sample.iterrows():
        for section_key in MANDATORY_SECTION_KEYS:
            key = (entry["sample_id"], entry["document_id"], section_key)
            if key in existing_keys:
                continue
            rows.append({
                "sample_id": entry["sample_id"],
                "document_id": entry["document_id"],
                "section_key": section_key,
                "reference_status": "",
                "reference_heading": "",
                "reference_quote": "",
                "page_start": "",
                "page_end": "",
                "printed_pages": "",
                "reviewer": "",
                "reviewed_at": "",
                "notes": "human annotation required",
            })
    frame = pd.DataFrame(rows, columns=EVAL_REFERENCE_COLUMNS)
    frame = frame.sort_values(["sample_id", "section_key"]).reset_index(drop=True)
    write_table(EVAL_REFERENCE_CSV, frame)
    return frame


def build_provisional_reference(sample: pd.DataFrame) -> pd.DataFrame:
    """A clearly labelled provisional reference from simple keyword markers.

    It exists so the metric pipeline can be exercised end-to-end before a human
    has annotated the 20 leaflets.  It is never presented as a manual reference
    and the report states that it must be replaced.
    """
    notices = read_table(META_DIR / "notices.csv", NOTICE_COLUMNS)
    by_id = {row["document_id"]: row for row in notices.to_dict("records")}
    rows = []
    for _, entry in sample.iterrows():
        notice = by_id.get(entry["document_id"], {})
        text = _notice_text(notice)
        for section_key in MANDATORY_SECTION_KEYS:
            pattern = _PROVISIONAL_RE[section_key]
            match = pattern.search(text)
            if not match:
                rows.append({
                    "sample_id": entry["sample_id"],
                    "document_id": entry["document_id"],
                    "section_key": section_key,
                    "reference_status": NOT_FOUND_IN_DOCUMENT,
                    "reference_heading": "",
                    "reference_quote": "",
                    "page_start": "", "page_end": "", "printed_pages": "",
                    "reviewer": "PROVISIONAL_AUTOMATED",
                    "reviewed_at": _now(),
                    "notes": "provisional keyword scan; replace with human annotation",
                })
                continue
            start = match.start()
            next_match = _ALL_MARKERS.search(text, match.end())
            end = next_match.start() if next_match else min(len(text), start + 6000)
            end = min(end, start + 6000)
            quote = text[match.end():end].strip()
            heading_line = text[start:start + 200].splitlines()[0].strip()
            rows.append({
                "sample_id": entry["sample_id"],
                "document_id": entry["document_id"],
                "section_key": section_key,
                "reference_status": FOUND,
                "reference_heading": heading_line,
                "reference_quote": quote,
                "page_start": "", "page_end": "", "printed_pages": "",
                "reviewer": "PROVISIONAL_AUTOMATED",
                "reviewed_at": _now(),
                "notes": "provisional keyword scan; replace with human annotation",
            })
    frame = pd.DataFrame(rows, columns=EVAL_REFERENCE_COLUMNS)
    frame = frame.sort_values(["sample_id", "section_key"]).reset_index(drop=True)
    write_table(EVAL_PROVISIONAL_CSV, frame)
    return frame


def _normalise(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").replace("\u00a0", " ")).strip()


def _similarity(reference: str, predicted: str) -> float:
    left, right = _normalise(reference)[:8000], _normalise(predicted)[:8000]
    if not left or not right:
        return 0.0
    return round(difflib.SequenceMatcher(None, left, right).ratio(), 4)


def _numbers_preserved(reference: str, predicted: str) -> str:
    values = numeric_signature(reference)
    if not values:
        return ""
    body = _normalise(predicted).lower()
    return "yes" if all(value in body for value in values) else "no"


def _page_match(reference: pd.Series, predicted: pd.Series) -> str:
    page = str(reference.get("page_start", "") or "").strip()
    if not page:
        return ""
    pages = str(predicted.get("pages", "") or "")
    return "yes" if page in [part for part in pages.split(";") if part] else "no"


def _manual_annotations(reference: pd.DataFrame) -> pd.DataFrame:
    if reference.empty or "reference_status" not in reference.columns:
        return reference.iloc[0:0]
    status = reference["reference_status"].astype(str).str.strip()
    return reference[status.isin(REFERENCE_STATUSES)]


def score(reference_path: Path | None = None) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Score the current extracted sections against the reference."""
    sample = read_table(EVAL_SAMPLE_CSV, EVAL_SAMPLE_COLUMNS)
    manual = read_table(EVAL_REFERENCE_CSV, EVAL_REFERENCE_COLUMNS)
    annotated = _manual_annotations(manual)
    reference_source = "manual_reference.csv"
    if annotated.empty and EVAL_PROVISIONAL_CSV.exists():
        reference = read_table(EVAL_PROVISIONAL_CSV, EVAL_REFERENCE_COLUMNS)
        annotated = _manual_annotations(reference)
        reference_source = "provisional_reference.csv (NOT manual)"
    else:
        reference = annotated

    extracted = read_table(EXTRACTED_SECTIONS_CSV, EXTRACTED_SECTION_COLUMNS)
    if extracted.empty:
        scores = pd.DataFrame(columns=EVAL_SCORE_COLUMNS)
        metrics = pd.DataFrame()
        _write_report(scores, metrics, reference_source, 0)
        return scores, metrics

    lookup = {}
    for _, row in extracted[extracted["document_type"] == "NOTICE"].iterrows():
        lookup[(row["document_id"], row["section_key"])] = row

    score_rows = []
    for _, reference_row in annotated.iterrows():
        predicted = lookup.get((reference_row["document_id"],
                                reference_row["section_key"]))
        expected = reference_row["reference_status"]
        if predicted is None:
            predicted_status = NOT_FOUND_IN_DOCUMENT
            method, content = "", ""
            predicted_row = pd.Series(dtype=object)
        else:
            predicted_status = predicted["status"]
            method, content = predicted["extraction_method"], predicted["content"]
            predicted_row = predicted
        both_found = expected == FOUND and predicted_status == FOUND
        exact = ""
        similarity = ""
        numbers = ""
        page = ""
        if both_found:
            reference_quote = reference_row.get("reference_quote", "")
            ref_norm = _normalise(reference_quote)
            pred_norm = _normalise(content)
            exact = "yes" if ref_norm and pred_norm and (
                ref_norm in pred_norm or pred_norm in ref_norm) else "no"
            similarity = _similarity(reference_quote, content)
            numbers = _numbers_preserved(reference_quote, content)
            page = _page_match(reference_row, predicted_row)
        score_rows.append({
            "sample_id": reference_row["sample_id"],
            "document_id": reference_row["document_id"],
            "section_key": reference_row["section_key"],
            "expected_status": expected,
            "predicted_status": predicted_status,
            "status_match": "yes" if expected == predicted_status else "no",
            "content_exact_match": exact,
            "content_similarity": similarity,
            "numbers_match": numbers,
            "page_match": page,
            "predicted_method": method,
            "notes": reference_row.get("notes", ""),
        })
    scores = pd.DataFrame(score_rows, columns=EVAL_SCORE_COLUMNS)
    metrics = _metrics(scores)
    write_table(EVAL_SCORES_CSV, scores)
    write_table(EVAL_METRICS_CSV, metrics)
    _write_report(scores, metrics, reference_source, len(sample))
    return scores, metrics


def _safe_div(numerator: float, denominator: float) -> float:
    return round(numerator / denominator, 4) if denominator else 0.0


def _metrics(scores: pd.DataFrame) -> pd.DataFrame:
    if scores.empty:
        return pd.DataFrame(columns=["scope", "section_key", "rows", "status_accuracy",
                                     "found_precision", "found_recall", "found_f1",
                                     "content_exact_rate", "mean_similarity",
                                     "numbers_preserved_rate", "page_accuracy"])
    rows = []

    def add(scope: str, data: pd.DataFrame, section_key: str = "ALL"):
        expected_found = data[data["expected_status"] == FOUND]
        predicted_found = data[data["predicted_status"] == FOUND]
        true_positive = data[(data["expected_status"] == FOUND)
                             & (data["predicted_status"] == FOUND)]
        precision = _safe_div(len(true_positive), len(predicted_found))
        recall = _safe_div(len(true_positive), len(expected_found))
        f1 = _safe_div(2 * precision * recall, precision + recall)
        both = data[(data["expected_status"] == FOUND)
                    & (data["predicted_status"] == FOUND)]
        similarity = pd.to_numeric(both["content_similarity"], errors="coerce").dropna()
        numeric = both[both["numbers_match"].isin(["yes", "no"])]
        pages = both[both["page_match"].isin(["yes", "no"])]
        rows.append({
            "scope": scope,
            "section_key": section_key,
            "rows": len(data),
            "status_accuracy": _safe_div((data["status_match"] == "yes").sum(), len(data)),
            "found_precision": precision,
            "found_recall": recall,
            "found_f1": f1,
            "content_exact_rate": _safe_div((both["content_exact_match"] == "yes").sum(), len(both)),
            "mean_similarity": round(float(similarity.mean()), 4) if len(similarity) else "",
            "numbers_preserved_rate": _safe_div((numeric["numbers_match"] == "yes").sum(), len(numeric)),
            "page_accuracy": _safe_div((pages["page_match"] == "yes").sum(), len(pages)),
        })

    add("overall", scores)
    for section_key, group in scores.groupby("section_key"):
        add("section", group, section_key)
    return pd.DataFrame(rows)


def _write_report(scores: pd.DataFrame, metrics: pd.DataFrame,
                  reference_source: str, sample_size: int):
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Extraction evaluation",
        "",
        f"Generated: {_now()}",
        f"Sample size: {sample_size} patient notices",
        f"Reference used: **{reference_source}**",
        "",
    ]
    if reference_source.startswith("provisional"):
        lines += [
            "> **The quantitative rows below are provisional.** They were produced",
            "> by a simple independent keyword scan, not by a human. Replace",
            "> `data/evaluation/manual_reference.csv` annotations and rerun",
            "> `python main.py extract-eval --score` before quoting these numbers.",
            "",
        ]
    if scores.empty:
        lines += ["No annotated reference rows yet. Fill",
                  "`data/evaluation/manual_reference.csv` and rerun the scorer.", ""]
    else:
        overall = metrics[metrics["scope"] == "overall"].iloc[0]
        lines += [
            "## Overall",
            "",
            "| metric | value |",
            "|---|---|",
            f"| annotated section rows | {int(overall['rows'])} |",
            f"| status accuracy | {overall['status_accuracy']:.3f} |",
            f"| FOUND precision | {overall['found_precision']:.3f} |",
            f"| FOUND recall | {overall['found_recall']:.3f} |",
            f"| FOUND F1 | {overall['found_f1']:.3f} |",
            f"| exact quote containment | {overall['content_exact_rate']:.3f} |",
            f"| mean text similarity | {overall['mean_similarity']} |",
            f"| numeric preservation | {overall['numbers_preserved_rate']:.3f} |",
            f"| page accuracy | {overall['page_accuracy']:.3f} |",
            "",
            "## Per section",
            "",
            "| section | rows | status acc. | precision | recall | F1 |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for _, row in metrics[metrics["scope"] == "section"].iterrows():
            lines.append(
                f"| {row['section_key']} | {int(row['rows'])} | "
                f"{row['status_accuracy']:.3f} | {row['found_precision']:.3f} | "
                f"{row['found_recall']:.3f} | {row['found_f1']:.3f} |"
            )
        lines += ["", "## Method", "",
                  "Status accuracy compares the reference status with the extractor",
                  "status. FOUND precision/recall use FOUND as the positive class.",
                  "Quote containment, similarity, numeric preservation and page",
                  "accuracy are computed only when both sides report FOUND.", ""]
    EVAL_REPORT_MD.write_text("\n".join(lines), encoding="utf-8")


def run_evaluation(size: int = 20, refresh_sample: bool = False,
                   provisional: bool = True, quiet: bool = False) -> dict:
    sample = build_sample(size=size, refresh=refresh_sample)
    manual = build_reference_template(sample)
    provisional_frame = build_provisional_reference(sample) if provisional else pd.DataFrame()
    scores, metrics = score()
    summary = {
        "sample": len(sample),
        "manual_annotated": len(_manual_annotations(manual)),
        "provisional_rows": len(provisional_frame),
        "scored_rows": len(scores),
        "report": str(EVAL_REPORT_MD),
        "sample_csv": str(EVAL_SAMPLE_CSV),
        "reference_csv": str(EVAL_REFERENCE_CSV),
        "provisional_csv": str(EVAL_PROVISIONAL_CSV) if provisional else "",
    }
    if not quiet:
        print("PHARMEAZOR - extraction evaluation")
        print("=" * 62)
        for key, value in summary.items():
            print(f"  {key:20s} {value}")
        if not metrics.empty:
            print()
            print(metrics.to_string(index=False))
    return summary
