"""Repeatable evaluation of the extraction stage.

The manual reference is kept in ``data/evaluation/manual_reference.csv`` and is
never written by the extractor.  A human fills ``reference_status`` (FOUND /
NOT_FOUND_IN_DOCUMENT / NEEDS_REVIEW) and, when possible, the exact quote and
page numbers.  Until a human has annotated a row, the scorer can use a clearly
labelled provisional reference generated by a simple, independent keyword
scan; the report states which reference was used.

Commands are exposed as ``python main.py extract-eval``.
"""
